function normalizeFirstName(raw: string): string {
  const first = (raw.trim().split(/[\s-]+/)[0] ?? "").toLowerCase();
  return first.normalize("NFD").replace(/\p{M}/gu, "");
}

export type StudentAvatarGender = "girl" | "boy";

export function genderFromFirstName(firstName: string): StudentAvatarGender {
  return FEMININE_FIRST_NAMES.has(normalizeFirstName(firstName))
    ? "girl"
    : "boy";
}
